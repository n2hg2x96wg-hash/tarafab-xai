function lookup(node: Strings | string | undefined, key: string): string | undefined {
  for (const part of key.split('.')) {
    if (node == null || typeof node !== 'object') return undefined
    node = node[part]
  }
  return typeof node === 'string' && node.trim() !== '' ? node : undefined
}

export function walletText(locale: Locale, key: string, vars?: Record<string, string | number>) {
  const raw = lookup(W[locale], key) ?? lookup(W.en, key) ?? ''
  return vars ? raw.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : raw
}
