export function marketsText(locale: Locale, key: string, vars?: Record<string, string | number>) {
  const raw = M[locale]?.[key] || M.en[key] || key
  return vars ? raw.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : raw
}
